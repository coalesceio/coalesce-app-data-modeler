// Builds the DBML export of one model: one Table per node in the model, column labels/roles/tags
// as notes, business keys as pk, relations between its nodes as Refs, a TableGroup per location.
//
// Output sticks to the long-supported core of DBML so it imports into tools with older parsers:
// no schema-qualified table names (schemas only exist since DBML 2.4; the Coalesce location goes in
// the table note and its TableGroup instead) and no notes on indexes (only since 3.x). A node name
// used in two locations of the same model becomes <LOCATION>_<NAME>.

const Models = require("./models");

const BUSINESS_KEY_ROLE = "businessKeyPart";

const CARDINALITY = {
  "many-to-one": ">",
  "one-to-many": "<",
  "one-to-one": "-",
  "many-to-many": "<>",
};

const ident = (s) => (/^[A-Za-z_][A-Za-z0-9_]*$/.test(s) ? s : `"${String(s).replace(/"/g, '\\"')}"`);
const str = (s) => `'${String(s).replace(/\\/g, "\\\\").replace(/'/g, "\\'").replace(/\s*\n\s*/g, " ")}'`;
const type = (t) => (!t ? "unknown" : /^[A-Za-z_][A-Za-z0-9_]*(\(\s*\d+(\s*,\s*\d+)?\s*\))?$/.test(t) ? t : `"${t}"`);

// nodes: [{id, location, name, nodeType, description, columns: [{id, name, dataType, description, nullable}]}]
// model: { "<LOC>-<NAME>": modelDoc } as stored in model/nodes/*.yml
// vocab: parsed model/tags.yml
// types: node types [{id, name, color}]
// def:   model definition (name, type, include); only its nodes are exported
function generate({ nodes, model = {}, vocab = {}, types = [], def }) {
  const sources = nodes.filter((n) => Models.includes(def, n));
  const nameCount = new Map();
  for (const n of sources) nameCount.set(n.name, (nameCount.get(n.name) || 0) + 1);
  const tableRef = (n) => ident(nameCount.get(n.name) > 1 ? `${n.location}_${n.name}` : n.name);
  const typeOf = (n) => types.find((t) => t.id === n.nodeType);
  const roleLabel = (k) => vocab.roles?.[k]?.label || humanize(k);
  const tagLabel = (k) => vocab.tags?.[k]?.label || humanize(k);
  const docFor = (s) => model[`${s.location}-${s.name}`] || {};
  const colMeta = (doc, col) =>
    (doc.columns || []).find((c) => c.id && c.id === col.id) ||
    (doc.columns || []).find((c) => c.name === col.name) ||
    {};

  const out = [
    `// DBML export of the "${def?.name}" model${def?.type ? ` (${def.type})` : ""}.`,
    "// Generated by the Data Modeler app from model/models/*.yml, model/nodes/*.yml and model/tags.yml - edit those, not this file.",
    `// Table types: ${[...new Set((def?.include?.nodeTypes || []).map((id) => Models.tableType(types.find((t) => t.id === id) || { id }).type))].sort().join(", ") || "any"}`,
    `// Locations: ${(def?.include?.locations || []).join(", ") || "any"}`,
    "",
  ];

  const byLocation = new Map();
  for (const s of sources) {
    const doc = docFor(s);
    const meta = s.columns.map((c) => [c, colMeta(doc, c)]);
    const keys = meta.filter(([, m]) => (m.roles || []).includes(BUSINESS_KEY_ROLE)).map(([c]) => c);

    const tt = Models.tableType(typeOf(s) || { id: s.nodeType });
    const tableNote = [
      doc.node?.label && `Display label: ${doc.node.label}`,
      `Type: ${tt.type}`,
      tt.subtype && `Subtype: ${tt.subtype}`,
      `Location: ${s.location}`,
      s.planned && "Status: planned new node (not built yet)",
      s.status === "changed" && "Status: planned changes",
      s.status === "deleted" && "Status: planned for deletion",
      s.description && `Description: ${s.description}`,
    ].filter(Boolean);

    const color = typeOf(s)?.color;
    out.push(`Table ${tableRef(s)}${/^#[0-9a-f]{6}$/i.test(color || "") ? ` [headercolor: ${color}]` : ""} {`);
    for (const [c, m] of meta) {
      const settings = [];
      if (keys.length === 1 && keys[0] === c) settings.push("pk");
      if (c.nullable === false) settings.push("not null");
      const note = [
        m.label && `label: ${m.label}`,
        m.roles?.length && `roles: ${m.roles.map(roleLabel).join(", ")}`,
        m.tags?.length && `tags: ${m.tags.map(tagLabel).join(", ")}`,
        c.description && `description: ${c.description}`,
      ].filter(Boolean);
      if (note.length) settings.push(`note: ${str(note.join(" | "))}`);
      out.push(`  ${ident(c.name)} ${type(c.dataType)}${settings.length ? ` [${settings.join(", ")}]` : ""}`);
    }
    if (keys.length > 1) {
      out.push("", "  indexes {", `    (${keys.map((c) => ident(c.name)).join(", ")}) [pk] // business key`, "  }");
    }
    out.push("", `  Note: ${str(tableNote.join(" | "))}`, "}", "");

    if (!byLocation.has(s.location)) byLocation.set(s.location, []);
    byLocation.get(s.location).push(s);
  }

  const byId = new Map(sources.map((s) => [s.id, s]));
  const byKey = new Map(sources.map((s) => [`${s.location}-${s.name}`, s]));
  const refs = [];
  const usedNames = new Set();
  for (const s of sources) {
    for (const r of docFor(s).relations || []) {
      const t = byId.get(r.target?.id) || byKey.get(`${r.target?.location}-${r.target?.name}`);
      const pairs = (r.columns || []).filter((p) => p.source?.name && p.target?.name);
      const inWorkspace = nodes.some((n) => n.id === r.target?.id || (n.location === r.target?.location && n.name === r.target?.name));
      if (!t && inWorkspace) continue; // target exists but is not part of this model
      if (!t || !pairs.length) {
        refs.push(`// skipped relation ${r.label ? `"${r.label}" ` : ""}from ${s.location}.${s.name}: target node or columns not found`);
        continue;
      }
      const cols = (n, side) =>
        pairs.length === 1 ? ident(pairs[0][side].name) : `(${pairs.map((p) => ident(p[side].name)).join(", ")})`;
      let name = "";
      if (r.label) {
        const base = r.label.trim().replace(/[^A-Za-z0-9_]+/g, "_").replace(/^_+|_+$/g, "") || "rel";
        name = base;
        for (let i = 2; usedNames.has(name); i++) name = `${base}_${i}`;
        usedNames.add(name);
        name = ` ${/^[0-9]/.test(name) ? `r_${name}` : name}`;
      }
      const op = CARDINALITY[r.cardinality] || ">";
      refs.push(
        `Ref${name}: ${tableRef(s)}.${cols(s, "source")} ${op} ${tableRef(t)}.${cols(t, "target")}` +
          (r.label ? ` // ${r.label.replace(/\s*\n\s*/g, " ")}` : ""),
      );
    }
  }
  out.push("// Relationships", ...(refs.length ? refs : ["// None"]), "");

  for (const [loc, nodes] of byLocation) {
    out.push(`TableGroup ${ident(loc)} {`, ...nodes.map((n) => `  ${tableRef(n)}`), "}", "");
  }
  return out.join("\n");
}

function humanize(k) {
  const s = String(k).replace(/([a-z0-9])([A-Z])/g, "$1 $2").replace(/[_-]+/g, " ").toLowerCase();
  return s.charAt(0).toUpperCase() + s.slice(1);
}

module.exports = { generate, humanize, CARDINALITY };
